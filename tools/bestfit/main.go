// Command bestfit writes shell/bestfit_table.go: the runes Windows best-fit turns into a double quote, a backslash, a
// space or a tab, as internal/bestfit finds them on the Windows it runs on. Run it from the module's root, on Windows:
//
//	go run ./tools/bestfit
//
// The file holds the runes and, as comments, the byte each becomes and the code pages that give it. It holds no date,
// Windows build or machine detail, so two Windows machines that convert alike write the same bytes. It refuses to write
// a table without U+FF02 and U+FF3C, the fullwidth quotation mark and backslash the rule was written for.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"slices"
	"strconv"
	"strings"

	"github.com/birdtable/go-console/internal/bestfit"
)

// out is the file written, from the module's root.
const out = "shell/bestfit_table.go"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	hits, err := bestfit.Hits()
	if err != nil {
		return err
	}
	src, n, err := table(hits)
	if err != nil {
		return err
	}
	if err := os.WriteFile(out, src, 0o600); err != nil {
		return err
	}
	fmt.Printf("%s: %d runes\n", out, n)
	return nil
}

// table is the Go source of the table for hits, formatted, and the number of runes in it.
func table(hits []bestfit.Hit) ([]byte, int, error) {
	var runes []rune
	notes := map[rune][]string{}
	for _, h := range hits {
		if len(notes[h.Rune]) == 0 {
			runes = append(runes, h.Rune)
		}
		notes[h.Rune] = append(notes[h.Rune], name(h.Byte)+" on "+pages(h.Pages))
	}
	for _, must := range []rune{0xFF02, 0xFF3C} {
		if !slices.Contains(runes, must) {
			return nil, 0, fmt.Errorf("bestfit: the scan does not hold U+%04X, so the table is not written", must)
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/bestfit; DO NOT EDIT.\n\npackage shell\n\n")
	b.WriteString("// bestFitRunes is every rune above U+007F that Windows best-fit (WideCharToMultiByte with no flags) turns into the one\n")
	b.WriteString("// byte of a double quote, a backslash, a space or a tab on a Windows ANSI code page, ascending. The code pages asked\n")
	b.WriteString("// are " + pages(bestfit.Pages()) + ", and each line names the byte and the code\n")
	b.WriteString("// pages that give it. tools/bestfit writes the table on Windows from the system's own conversion, and a Windows test\n")
	b.WriteString("// holds it to that scan.\n")
	b.WriteString("var bestFitRunes = []rune{ //nolint:gochecknoglobals // the table: read, never written\n")
	for _, r := range runes {
		fmt.Fprintf(&b, "\t0x%04X, // %s\n", r, strings.Join(notes[r], "; "))
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, 0, fmt.Errorf("bestfit: the table does not format: %w", err)
	}
	return src, len(runes), nil
}

// name is the byte as the table's comment says it.
func name(b byte) string {
	switch b {
	case 0x09:
		return "tab"
	case 0x20:
		return "space"
	}
	return string(rune(b))
}

// pages is code pages as the table's comment lists them.
func pages(ps []int) string {
	var s []string
	for _, p := range ps {
		s = append(s, strconv.Itoa(p))
	}
	return strings.Join(s, " ")
}
